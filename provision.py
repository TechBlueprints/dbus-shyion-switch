#!/usr/bin/env python3
"""
Shyion Relay Provisioning Tool

Logs into the Shyion cloud, fetches the device list, and generates
config.ini for dbus-shyion-switch.

Usage:
    python3 provision.py [--email EMAIL] [--output PATH]

The script will prompt for your Shyion account password.
"""
import argparse
import configparser
import getpass
import json
import re
import sys

try:
    import requests
except ImportError:
    print("Error: 'requests' is required. Install with: pip install requests")
    sys.exit(1)

# ── Shyion backend ──────────────────────────────────────────────────
SHYION_API = "http://47.251.12.213:80"


def _transform_password(raw_password: str) -> str:
    """Transform the password as the Shyion app does before sending.

    The app strips period characters and truncates to 15 characters.
    """
    pw = raw_password.replace(".", "")
    return pw[:15]


class ShyionAPI:
    """Client for the Shyion backend API."""

    def __init__(self):
        self.session = requests.Session()
        self.session.headers.update({
            "Content-Type": "application/json",
            "accept-encoding": "gzip",
            "registertype": "0",
        })
        self.jwt = None
        self.spm = None
        self.bscred = None

    def _do_login(self, email: str, password: str):
        """Internal login helper. Returns user data dict on success."""
        resp = self.session.post(
            f"{SHYION_API}/api/base/public/user/login",
            json={"email": email, "password": password},
        )
        resp.raise_for_status()
        data = resp.json()
        if data.get("code") != 1:
            msg = data.get("msg", "Unknown error")
            raise RuntimeError(f"Login failed: {msg} (code={data.get('code')})")

        result = data["data"]
        self.jwt = result["Authorization"]
        self.spm = result["Spm"]
        self.bscred = result["Bscred"]

        self.session.headers.update({
            "authorization": self.jwt,
            "spm": self.spm,
            "bscred": self.bscred,
        })

        return result

    def login(self, email: str, password: str):
        """Login with transformed password (periods stripped, truncated)."""
        return self._do_login(email, _transform_password(password))

    def login_raw(self, email: str, password: str):
        """Login with raw password as-is."""
        return self._do_login(email, password)

    def get_devices(self):
        """Fetch the device list. Returns list of device dicts."""
        resp = self.session.post(
            f"{SHYION_API}/api/device/devicerelation/devicerelationlist",
            json={},
        )
        resp.raise_for_status()
        data = resp.json()
        if data.get("code") != 1:
            msg = data.get("msg", "Unknown error")
            raise RuntimeError(f"Failed to fetch devices: {msg}")

        return data["data"]["list"]


def reverse_mac(uniqueid: str) -> str:
    """Convert a Shyion uniqueid to the actual BLE MAC address.

    The Shyion backend stores the MAC bytes in reversed order.
    E.g. uniqueid 'FFEEDDCCBBAA' → BLE MAC 'AA:BB:CC:DD:EE:FF'.
    """
    uid = uniqueid.upper().strip().replace(":", "")
    if len(uid) != 12:
        return uniqueid

    octets = [uid[i:i+2] for i in range(0, 12, 2)]
    return ":".join(reversed(octets))


def format_mac(hex_str: str) -> str:
    """Format a hex string as colon-separated MAC."""
    uid = hex_str.upper().strip().replace(":", "")
    if len(uid) == 12:
        return ":".join(uid[i:i+2] for i in range(0, 12, 2))
    return hex_str


def generate_config(devices: list, output_path: str):
    """Write config.ini with all discovered devices."""
    cfg = configparser.ConfigParser()

    cfg["DEFAULT"] = {
        "scan_interval": "60",
        "bluetooth_adapters": "",
        "name_prefixes": "BBKS",
        "poll_interval_hours": "24",
    }

    for dev in devices:
        name = dev.get("name", "Unknown")
        uniqueid = dev.get("uniqueid", "")
        if not uniqueid:
            continue

        if dev.get("devicetype") != 1:
            continue

        section = re.sub(r"[^a-zA-Z0-9_-]", "_", name)
        cfg[section] = {
            "name": name,
            "mac": reverse_mac(uniqueid),
            "shyion_uniqueid": format_mac(uniqueid),
            "model": dev.get("devicename", ""),
            "shyion_id": str(dev.get("id", "")),
            "device_type_id": str(dev.get("deviceid", "")),
        }

    with open(output_path, "w") as f:
        f.write("# Shyion Relay Configuration\n")
        f.write("# Generated by provision.py\n")
        f.write("#\n")
        f.write("# 'mac' is the actual BLE advertisement MAC address.\n")
        f.write("# 'shyion_uniqueid' is the Shyion backend identifier (byte-reversed MAC).\n")
        f.write("#\n\n")
        cfg.write(f)

    print(f"  Written to {output_path}")


def main():
    parser = argparse.ArgumentParser(description="Shyion Relay Provisioning")
    parser.add_argument("--email", help="Shyion account email")
    parser.add_argument(
        "--output", default="config.ini",
        help="Output config file (default: config.ini)",
    )
    args = parser.parse_args()

    print("=" * 50)
    print("  Shyion Relay Provisioning Tool")
    print("=" * 50)

    email = args.email
    if not email:
        email = input("Shyion account email: ").strip()
    password = getpass.getpass("Password: ")

    print()
    print(f"  Account : {email}")
    print(f"  Output  : {args.output}")

    print("\nStep 1: Logging into Shyion cloud...")
    api = ShyionAPI()
    try:
        user = api.login(email, password)
        print(f"  Logged in as: {user.get('userName', '?')} ({user.get('email')})")
    except RuntimeError:
        try:
            api2 = ShyionAPI()
            user = api2.login_raw(email, password)
            api = api2
            print(f"  Logged in as: {user.get('userName', '?')} ({user.get('email')})")
        except RuntimeError as e:
            print(f"  {e}")
            return 1
    except requests.RequestException as e:
        print(f"  Connection error: {e}")
        return 1

    print("\nStep 2: Fetching devices...")
    try:
        devices = api.get_devices()
    except RuntimeError as e:
        print(f"  {e}")
        return 1

    if not devices:
        print("  No devices found!")
        return 1

    switches = [d for d in devices if d.get("devicetype") == 1]
    print(f"  Found {len(devices)} device(s), {len(switches)} BLE switch(es):")
    for dev in switches:
        name = dev.get("name", "?")
        uniqueid = dev.get("uniqueid", "?")
        model = dev.get("devicename", "?")
        battery = dev.get("electric", "?")
        locked = "locked" if dev.get("islocked") else "unlocked"
        ble_mac = reverse_mac(uniqueid)
        print(f"    - {name}")
        print(f"      BLE MAC: {ble_mac}  Model: {model}")
        print(f"      Battery: {battery}  State: {locked}")

    print(f"\nStep 3: Writing {args.output}...")
    generate_config(switches, args.output)

    print("\n" + "=" * 50)
    print("  Done! Copy config.ini to your Cerbo GX:")
    print(f"    scp {args.output} root@<cerbo>:/data/apps/dbus-shyion-switch/config.ini")
    print("=" * 50)
    return 0


if __name__ == "__main__":
    sys.exit(main())
